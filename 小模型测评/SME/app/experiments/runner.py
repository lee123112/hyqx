"""Fixed-protocol experiment runner shared by operators and offline tools.

The service path is intentionally thin: an engine produces per-sample
measurements, the existing ``rules.evaluate`` makes the pass/fail decision, and
the engine audit block is retained next to the result.  An offline experiment
uses the same functions so a report generated by a script matches a report
generated through the API.
"""
from __future__ import annotations

from typing import Any

from ..core.envelope import ApiError
from ..core.ids import now
from ..engines import service as engine_service
from ..eval import rules, templates


def run_experiment(type_: str, samples: list[dict[str, Any]],
                   config: dict[str, Any] | None = None, *,
                   seed: int = 42, strict: bool = True,
                   data_manifest: dict[str, Any] | None = None) -> dict[str, Any]:
    """Run one fixed-protocol measurement and return an auditable record.

    This function does not invent a baseline: the caller supplies the fixed
    sample/evaluation corpus, and the engine decides whether a baseline can be
    trained or measured.  A missing engine/asset remains an explicit failure.
    """
    if type_ not in templates.TEMPLATES:
        raise ApiError(422, "CONFIG_INVALID", "请选择有效的评测类型")
    if not isinstance(samples, list) or not samples:
        raise ApiError(422, "SAMPLE_INVALID", "固定协议实验至少需要一条样本")
    effective_config = config if isinstance(config, dict) else templates.default_config(type_)
    rules.validate_config(type_, effective_config)

    measured = engine_service.measure_samples(
        type_, samples, effective_config, seed=seed, strict=strict)
    merged = engine_service.apply_measurements(samples, measured)
    evaluation = rules.evaluate(type_, merged, effective_config)
    audit = engine_service.audit_block(measured)
    if audit.get("provenance"):
        evaluation["provenance"] = audit["provenance"]
    evaluation["engine"] = audit

    return {
        "schemaVersion": "1.0",
        "createdAt": now(),
        "type": type_,
        "seed": seed,
        "strict": bool(strict),
        "sampleCount": len(samples),
        "config": effective_config,
        "dataManifest": data_manifest or {},
        "engine": audit,
        "result": evaluation,
        "samples": merged,
    }
